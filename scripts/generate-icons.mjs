import { writeFile } from "node:fs/promises";
const names = ["home", "search", "bell", "user-round", "settings", "shield", "pen-line", "message-circle", "arrow-up-right", "map-pin", "heart", "eye", "link", "ellipsis", "play"];
const icons = {};
for (const name of names) {
  const { __iconData } = await import(`lucide-react/icons/${name === "home" ? "house" : name}`);
  if (!__iconData?.node) throw new Error(`Lucide metadata unavailable for ${name}`);
  icons[name] = __iconData.node.map(([tag, { key, ...attributes }]) => [tag, attributes]);
}
await writeFile(
  "src/lib/icon-data.ts",
  `// Lucide (ISC). Generated by scripts/generate-icons.mjs; see docs/lucide-license.txt.\nexport type IconName = ${names.map((n) => JSON.stringify(n)).join(" | ")};\nexport const iconData: Record<IconName, [string, Record<string, string | number>][] > = ${JSON.stringify(icons, null, 2)};\n`
);
